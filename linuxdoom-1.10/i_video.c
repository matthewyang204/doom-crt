// Simple 4x5 bitmap font for digits 0-9 (1 = pixel on, 0 = off)
// Each digit is 4 pixels wide, 5 pixels tall
static const unsigned char fps_font[10][5] = {
    // 0
    { 0b1110, 0b1010, 0b1010, 0b1010, 0b1110 },
    // 1
    { 0b0100, 0b1100, 0b0100, 0b0100, 0b1110 },
    // 2
    { 0b1110, 0b0010, 0b1110, 0b1000, 0b1110 },
    // 3
    { 0b1110, 0b0010, 0b0110, 0b0010, 0b1110 },
    // 4
    { 0b1010, 0b1010, 0b1110, 0b0010, 0b0010 },
    // 5
    { 0b1110, 0b1000, 0b1110, 0b0010, 0b1110 },
    // 6
    { 0b1110, 0b1000, 0b1110, 0b1010, 0b1110 },
    // 7
    { 0b1110, 0b0010, 0b0100, 0b1000, 0b1000 },
    // 8
    { 0b1110, 0b1010, 0b1110, 0b1010, 0b1110 },
    // 9
    { 0b1110, 0b1010, 0b1110, 0b0010, 0b1110 }
};

// Draw a single digit at position (x, y) with given color
void draw_digit(byte* screen, int x, int y, int digit, byte color) {
    if (digit < 0 || digit > 9) return;
    if (x < 0 || y < 0 || x + 4 > SCREENWIDTH || y + 5 > SCREENHEIGHT) return;

    const unsigned char* font_data = fps_font[digit];
    for (int row = 0; row < 5; row++) {
        unsigned char bits = font_data[row];
        for (int col = 0; col < 4; col++) {
            if (bits & (0x8 >> col)) {
                screen[(y + row) * SCREENWIDTH + (x + col)] = color;
            }
        }
    }
}

// Draw the FPS meter in the top-left corner
void draw_fps_meter(byte* screen, int current_fps) {
    int x = 2;
    int y = 2;
    byte color = 0xFC;  // A bright yellow-ish color from DOOM palette

    int fps_val = current_fps;
    int digits[4] = { -1, -1, -1, -1 };
    int digit_count = 0;

    if (fps_val == 0) {
        digits[0] = 0;
        digit_count = 1;
    } else {
        int temp = fps_val;
        while (temp > 0 && digit_count < 4) {
            digits[3 - digit_count] = temp % 10;
            temp /= 10;
            digit_count++;
        }
    }

    int draw_x = x;
    for (int i = 0; i < 4; i++) {
        if (digits[i] >= 0) {
            draw_digit(screen, draw_x, y, digits[i], color);
            draw_x += 5;
        }
    }
}
int app_proc( app_t* app, void* user_data )
{
	#ifndef __wasm__
		app_screenmode( app, APP_SCREENMODE_FULLSCREEN );
	#else
		app_screenmode( app, APP_SCREENMODE_WINDOW );
	#endif
	app_interpolation( app, APP_INTERPOLATION_NONE );

    app_displays_t displays = app_displays( app );
    if( displays.count > 0 ) {
        int disp = 0;
        for( int i = 0; i < displays.count; ++i ) {
            if( displays.displays[ i ].x == 0 && displays.displays[ i ].y == 0 ) {
                disp = i;
                break;
            }
        }
        int scrwidth = displays.displays[ disp ].width - 80;
        int scrheight = displays.displays[ disp ].height - 80;
        int aspect_width = (int)( ( scrheight * 4.25f ) / 3 );
        int aspect_height = (int)( ( scrwidth * 3 ) / 4.25f );
        int target_width, target_height;
        if( aspect_height <= scrheight ) {
            target_width = scrwidth;
            target_height = aspect_height;
        } else {
            target_width = aspect_width;
            target_height = scrheight;
        }
        
        int x = displays.displays[ disp ].x + ( displays.displays[ disp ].width - target_width ) / 2;
        int y = displays.displays[ disp ].y + ( displays.displays[ disp ].height - target_height ) / 2;
        int w = target_width;
        int h = target_height;
        app_window_pos( app, x, y );
        app_window_size( app, w, h );
    }


    uint8_t* screen_buffer_xbgr = (uint8_t*)malloc( SCREENWIDTH * SCREENHEIGHT * 4 );

    frametimer_t* frametimer = frametimer_create( 0);
    frametimer_lock_rate( frametimer, 0 );  // Set to 0 for unlimited FPS

    crtemu_t* crtemu = crtemu_create( CRTEMU_TYPE_LITE,0 );

    APP_U32 empty = 0;
    app_pointer( app, 1, 1, &empty, 0, 0 );

    tsf* sound_font = tsf_load_memory( soundfont, sizeof( soundfont ) );
    app_sound( app, SAMPLECOUNT * 4 * 2, sound_callback, sound_font );
	
	#ifndef __wasm__
	thread_signal_raise( &vblank_signal );
	#endif
	#ifdef __wasm__
    // WebAssembly has no real threads so we use coroutines which can switch context between two
    // callstacks to simulate the behavior from native platforms
    user_coro = WaCoroInitNew( user_thread_proc, "user_thread_proc", 0, 0 );
	WaCoroSwitch(user_coro);
    #endif
	
    while( thread_atomic_int_load(&app_running) && app_yield( app ) != APP_STATE_EXIT_REQUESTED )
    {
		app_input_t input = app_input( app );
		for( int i = 0; i < input.count; ++i ) {
			if( input.events[i].type==APP_INPUT_KEY_DOWN ) {
				if( input.events[i].data.key == APP_KEY_F5 ) {
					fps_show = !fps_show;  // Toggle FPS display
				} else if( input.events[i].data.key < APP_KEYCOUNT ) {
					keystate[input.events[i].data.key] = 1;
				}
			} else if( input.events[i].type==APP_INPUT_KEY_UP ) {
				if( input.events[i].data.key < APP_KEYCOUNT ) {
					keystate[input.events[i].data.key] = 0;
				}
			} else if( input.events[i].type==APP_INPUT_MOUSE_DELTA ) {
				mouserelx = (int)(input.events[i].data.mouse_delta.x*8.0f); 
				mouserely = (int)(input.events[i].data.mouse_delta.y*8.0f);
			}
		}
        if( app_screen )
        {
            // Update FPS counter based on actual elapsed time (every 1 second)
            float delta = frametimer_delta_time(frametimer);
            fps_time_accumulator += delta;

            if (fps_time_accumulator >= 1.0f) {
                int current_frame = frametimer_frame_counter(frametimer);
                fps_current = current_frame - fps_last_frame;
                fps_last_frame = current_frame;
                fps_time_accumulator = 0.0f;
            }

            // Draw FPS meter if enabled
            if (fps_show) {
                draw_fps_meter(app_screen, fps_current);
            }

            // ...existing code...
            for( int i = 0; i < SCREENWIDTH * SCREENHEIGHT; ++i )
            {
                uint8_t scr = app_screen[ i ];
                screen_buffer_xbgr[ i * 4 + 3] = 0xff;
                screen_buffer_xbgr[ i * 4 ] = app_palette[ scr * 3 ];
                screen_buffer_xbgr[ i * 4 + 1] = app_palette[ scr * 3 + 1 ];
                screen_buffer_xbgr[ i * 4 + 2] = app_palette[ scr * 3 + 2 ];
            }
        }

        frametimer_update( frametimer );
        ++g_tickcount;
		#ifndef __wasm__
		thread_signal_raise( &vblank_signal );
		#endif
        crtemu_present( crtemu, ( g_tickcount * 1000000ULL) / TICRATE, (APP_U32*)screen_buffer_xbgr, SCREENWIDTH, SCREENHEIGHT, 0xffffff, 0x000000 );
        app_present( app, 0, 0, 0, 0xffffffff, 0x00000000);
		#ifdef __wasm__
			WaCoroSwitch(user_coro);
		#endif
    }
	app_sound( app, 0, NULL, NULL );
    tsf_close( sound_font );	
    free( screen_buffer_xbgr );
	return 0;
}


